import type { Food, Nutrients } from '../core/types.ts';

/**
 * Food composition table, Indian-first.
 *
 * Every row is per 100 g **as eaten**: a curry is stored cooked and finished,
 * with the oil already in it, because that is the only weight anyone can
 * estimate by eye. Values are rounded from public composition tables (IFCT
 * 2017 for Indian dishes, USDA FDC for everything else) and from typical
 * home-kitchen recipes where a dish has no single official entry. They are
 * good to roughly ±10%, which is well inside the error of guessing a portion.
 *
 * `each` is the weight of one of the item — one roti, one idli, one samosa.
 * `portions` is the weight of a named household measure of that food, so
 * "1 katori dal" resolves without anyone owning a kitchen scale.
 */

type Macros = [kcal: number, protein: number, carbs: number, fat: number, fiber: number];

interface Extra {
  each?: number;
  portions?: Record<string, number>;
  density?: number;
}

function f(id: string, name: string, aliases: string, m: Macros, tags: string, extra: Extra = {}): Food {
  const per100g: Nutrients = { kcal: m[0], protein: m[1], carbs: m[2], fat: m[3], fiber: m[4] };
  return {
    id,
    name,
    aliases: aliases ? aliases.split('|').map((a) => a.trim()).filter(Boolean) : [],
    per100g,
    tags: tags.split(' ').filter(Boolean),
    ...extra,
  };
}

